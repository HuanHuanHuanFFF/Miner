"""C3 proof2: explicitly consume the observed cap bind; no mutation of proof1."""
from pathlib import Path
import datetime
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
OLD = ROOT / "candidates/r26-c-658-deferred-extension-proof1"
NEW = ROOT / "candidates/r26-c-658-deferred-extension-proof2"
OUT = ROOT / "evidence/round26/extension90m/proof"
FAIL = ROOT / "evidence/round26/38267162180/gate-90-c3-proof1/exact-gate/exact-gate"

CAP = r'''theorem c3_cap_spec (rem : Std.Usize) :
    (if rem < 258#usize then ok rem else ok 258#usize) ⦃ fun cap =>
      cap.val ≤ 258 ∧ cap.val ≤ rem.val ⦄ := by
  split <;> simp only [Std.WP.spec_ok] <;> scalar_tac

'''

BODY = r'''  rw [slot.c3_emit_step]
  have hmax : input.length ≤ Std.Usize.max := Std.Slice.length_ineq input
  step*
  -- The real proof1 goal stops at this exact cap bind. The inferred argument
  -- avoids referencing the inaccessible name generated by step* for rem.
  apply Std.WP.spec_bind (c3_cap_spec _)
  intro cap hcap
  obtain ⟨hcap258, hcaprem⟩ := hcap
  have hcap_end : pos.val + cap.val + 8 ≤ input.length := by scalar_tac
  step*
  all_goals first
    | (match goal with
       | hm : Matches input _ pos.val ?full |- _ =>
         apply c3_write_post (input := input) (out := out) (pos := pos)
           (d := d) (full := full) (ntok := ntok)
         all_goals first | assumption | (simp only [LZ77.mkMatch, LZ77.MATCH_BASE]; scalar_tac))
    | (exact ⟨by scalar_tac, by scalar_tac, by scalar_tac,
          by assumption, by assumption⟩)
    | (apply Std.WP.spec_mono (emit_step_spec input out pos d _ lits ntok
          hout hpos hntok hdec)
       intro r hr
       exact hr)
    | (apply Std.WP.spec_mono (emit_lits_spec input out pos lits ntok
          hout (by omega) hntok hdec)
       rintro ⟨⟨t, k⟩, o⟩ ⟨h1, h2, h3, h4, h5⟩
       exact ⟨by omega, h2, h3, h4, h5⟩)

'''


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def dump(path, obj):
    path.write_bytes((json.dumps(obj, indent=2, ensure_ascii=False)+"\n").encode())


def main():
    assert not NEW.exists(), NEW
    raw = (OLD / "parse.rs").read_bytes()
    oldlean = (OLD / "Parse.lean").read_bytes()
    assert sha(raw) == "58324f244b6deb669e4a4af523a09e5900a016d027b32cc90c785363a19b8da7"
    assert sha(oldlean) == "dc80e9ddc7464f2f4233dc928f0059dc0709da67bd3d075618e4927b5af84232"
    text = oldlean.decode()
    start = text.index("theorem c3_write_post")
    end = text.index("@[local step]\ntheorem c3_emit_step_spec", start)
    writer = text[start:end]
    writer = writer.replace("{pos d full ntok ntok1 end1 a : Std.Usize}",
                            "{pos d ntok ntok1 end1 a : Std.Usize} {full : Nat}")
    writer = writer.replace("full.val", "full")
    text = text[:start] + writer + CAP + text[end:]
    start = text.index("  rw [slot.c3_emit_step]", text.index("theorem c3_emit_step_spec"))
    end = text.index("@[local step]\ntheorem fl_tw8_spec", start)
    text = text[:start] + BODY + text[end:]
    lean = text.encode()
    assert len(lean) <= 524288
    assert not re.search(rb"(?m)^\s*(axiom\s|.*\b(sorry|admit)\b)", lean)
    NEW.mkdir()
    (NEW / "parse.rs").write_bytes(raw)
    (NEW / "Parse.lean").write_bytes(lean)
    metadata = json.loads((OLD / "manifest.json").read_bytes())
    metadata.update({"candidate": NEW.name,
        "hashes": {"parse.rs": sha(raw), "Parse.lean": sha(lean)},
        "proof_status": "UNCOMPILED_ORIGINAL_GATE_NOT_RUN",
        "implementation_parent": "candidates/r26-c-658-deferred-extension",
        "proof_origin": {"path": OLD.relative_to(ROOT).as_posix()+"/Parse.lean", "sha256": sha(oldlean)},
        "proof_adaptation": "Explicit standalone cap spec and unconditional spec_bind after first step*. No direct generated rem reference or try around cap handling. Writer full becomes Nat and is captured from the actual Matches hypothesis, avoiding an inaccessible generated full name.",
        "prior_failure_receipt": (FAIL / "gate-receipt.json").relative_to(ROOT).as_posix(),
        "prior_failure_receipt_sha256": sha((FAIL / "gate-receipt.json").read_bytes()),
        "prior_failure_log_sha256": sha((FAIL / "logs/005-lake.log").read_bytes()),
        "proof_freeze_time_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "confirmation_status": "No post-freeze confirmation of this exact pair. Prior Rust-identical proof1 measurements remain separately bound.",
        "formal_submission_sent": False})
    metadata.pop("gate_receipt", None)
    metadata.pop("gate_receipt_sha256", None)
    metadata.pop("verification", None)
    dump(NEW / "manifest.json", metadata)
    entry = {"name": NEW.name, "path": NEW.relative_to(ROOT).as_posix(),
        "hashes": metadata["hashes"], "status": metadata["proof_status"],
        "rust_bytes": len(raw), "lean_bytes": len(lean), "lean_spare_bytes": 524288-len(lean),
        "control": False, "anchor": "public658", "comparison_baseline": "public658"}
    dump(OUT / "c3-proof2-entry.json", entry)
    (OUT / "C3-proof2-helper-UNCOMPILED.lean").write_bytes((writer+CAP+BODY).encode())
    print(json.dumps(entry, indent=2))


if __name__ == "__main__":
    main()
