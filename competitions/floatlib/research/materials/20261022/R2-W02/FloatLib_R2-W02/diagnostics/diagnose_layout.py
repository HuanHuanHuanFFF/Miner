#!/usr/bin/env python3
"""Self-contained synthetic diagnosis, not execution of Lean or FloatLib.

Index checks are exact Python integers.  The finite arithmetic oracle rounds
exact dyadic integers to binary32 RN-even, retaining subnormal and signed-zero
semantics.  Infinity, NaN and payload behavior are not executed by this script.
The finite oracle is not evidence of FloatLib's special-value policy.
"""
import json
import platform
import random
import shutil
import struct
import sys
from pathlib import Path


def unpack(w):
    sign = -1 if w >> 31 else 1
    E = (w >> 23) & 255
    f = w & 0x7FFFFF
    assert E != 255, "finite oracle only"
    return sign * (f if E == 0 else f + (1 << 23)), (-149 if E == 0 else E - 150)


def rne_int(v, shift):
    if shift <= 0:
        return v << (-shift)
    q, r = divmod(v, 1 << shift)
    half = 1 << (shift - 1)
    return q + (r > half or (r == half and (q & 1)))


def round_dyadic(v, e, negative_zero=False):
    sign = 0x80000000 if v < 0 or (v == 0 and negative_zero) else 0
    v = abs(v)
    if v == 0:
        return sign
    out_e = max(-149, e + v.bit_length() - 24)
    q = rne_int(v, out_e - e)
    if q == 0:
        return sign
    if q >= 1 << 24:
        q >>= 1
        out_e += 1
    if q < 1 << 23:
        assert out_e == -149
        return sign | q
    E = out_e + 150
    if E >= 255:
        raise OverflowError("test left finite-oracle domain")
    return sign | (E << 23) | (q - (1 << 23))


def mul(a, b):
    av, ae = unpack(a)
    bv, be = unpack(b)
    return round_dyadic(av * bv, ae + be, bool((a ^ b) >> 31))


def add(a, b):
    av, ae = unpack(a)
    bv, be = unpack(b)
    e = min(ae, be)
    v = (av << (ae - e)) + (bv << (be - e))
    return round_dyadic(v, e, bool((a & b) >> 31))


def dot(A, B):
    s = 0
    for a, b in zip(A, B):
        s = add(s, mul(a, b))
    return s


def bits_float(w):
    return struct.unpack(">f", w.to_bytes(4, "big"))[0]


def pack(batch, n, p, B):
    blocks = (p + 3) // 4
    out = []
    for b in range(batch):
        for g in range(blocks):
            for k in range(n):
                out.append(tuple(B[(b * n + k) * p + 4 * g + lane]
                    if 4 * g + lane < p else 0 for lane in range(4)))
    return out


def packed_bmm(batch, m, n, p, A, B):
    if batch * m * p == 0 or n == 0:
        return [0] * (batch * m * p)
    blocks = (p + 3) // 4
    P = pack(batch, n, p, B)
    out = []
    for row in range(batch * m):
        b = row // m
        for g in range(blocks):
            s = [0] * 4
            for k in range(n):
                av = A[row * n + k]
                v = P[(b * blocks + g) * n + k]
                for lane in range(4):
                    s[lane] = add(s[lane], mul(av, v[lane]))
            for lane in range(4):
                if 4 * g + lane < p:
                    out.append(s[lane])
    return out


def reference(batch, m, n, p, A, B):
    return [dot(A[(b * m + i) * n : (b * m + i + 1) * n],
                [B[(b * n + k) * p + j] for k in range(n)])
            for b in range(batch) for i in range(m) for j in range(p)]


def main():
    rng = random.Random(2026102202)  # Synthetic reproduction, not a bench answer cache.
    shapes = [(b, m, n, p) for b in range(3) for m in range(4)
        for n in range(6) for p in range(10)]
    count = 0
    edge = [0, 0x80000000, 1, 0x80000001, 0x007FFFFF, 0x00800000,
            0x3F800000, 0xBF800000, 0x3F000000, 0xBF000000]
    for shape in shapes:
        batch, m, n, p = shape
        A = [rng.choice(edge) for _ in range(batch*m*n)]
        B = [rng.choice(edge) for _ in range(batch*n*p)]
        expected = reference(*shape, A, B)
        actual = packed_bmm(*shape, A, B)
        assert actual == expected, (shape, actual, expected)
        count += len(actual)

    # Exact index identity; no arithmetic assumption and includes huge Nat values.
    index_checks = 0
    for _ in range(10000):
        batch = rng.randrange(1, 1 << 20)
        m = rng.randrange(1, 1 << 20)
        n = rng.randrange(1, 1 << 20)
        p = rng.randrange(1, 1 << 20)
        b = rng.randrange(batch)
        i = rng.randrange(m)
        j = rng.randrange(p)
        k = rng.randrange(n)
        row = b*m+i
        q = row*p+j
        b2, r = divmod(q, m*p)
        i2, j2 = divmod(r, p)
        assert (b2, i2, j2) == (b, i, j)
        blocks = (p+3)//4
        g, lane = divmod(j, 4)
        t = (b*blocks+g)*n+k
        pb, r = divmod(t, blocks*n)
        pg, pk = divmod(r, n)
        assert (pb, pg, pk, 4*pg+lane) == (b, g, k, j)
        assert (row*n+k) < batch*m*n
        assert ((b*n+k)*p+j) < batch*n*p
        index_checks += 1

    # RN-sensitive witnesses: each result is generated by integer arithmetic.
    # Original k-order: 2^24, 1, -2^24; chunk reassociation returns 1 instead of 0.
    a = [0x4B800000, 0x3F800000, 0xCB800000]
    original = dot(a, [0x3F800000]*3)
    wrong_order = add(add(a[0], a[2]), a[1])
    assert original == 0 and wrong_order == 0x3F800000
    # (1+2^-23)(1-2^-23) is below 1 by 2^-46; rounded mul=1.
