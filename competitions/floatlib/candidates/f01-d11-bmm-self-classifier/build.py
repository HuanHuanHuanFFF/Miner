"""Reproduce one two-endpoint classifier migration from exact a066 bytes.

Default is a dry run. --write creates Kernel/receipts once; existing files refuse
overwrite. --verify checks the frozen generated bytes without writing anything.
No Lean, Git, CI, downloads, or compiler options are invoked.
"""
from argparse import ArgumentParser
from datetime import datetime, timezone
from hashlib import sha256
from pathlib import Path
from types import SimpleNamespace
import ast
import json
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
PARENT = HERE.parent / 'f01-d10-bmm-direct-rows/Kernel.lean'
PARENT_SHA = 'a06608bdc419d4647af301bfdd617d52e4796c404661a28672a022eef4a10b78'
GATE = ROOT / 'competitions/floatlib/research/astra-collab-20261023-r7/upstream/gate-4b7e838.py'
GATE_SHA = '1eb74ef7479b0023c721e776cc5e4073af21c6662b4afffcf16a48a124d27194'
PARSER = HERE.parent / 'f01-r8-combined-result-guard/build.py'
PARSER_SHA = '58662bf7218de54978d999bfb424975732cf845708869e1d611dd712d7470f22'


def digest(raw):
    return sha256(raw).hexdigest()


def pinned(path, expected):
    raw = path.read_bytes()
    assert digest(raw) == expected, ('Pinned source mismatch', str(path))
    return raw


def load_functions(raw, names, env):
    nodes = [node for node in ast.parse(raw.decode()).body
             if isinstance(node, ast.FunctionDef) and node.name in names]
    assert {node.name for node in nodes} == set(names)
    exec(compile(ast.Module(body=nodes, type_ignores=[]), '<pinned pure helpers>', 'exec'), env)
    return env


def construct():
    parent = pinned(PARENT, PARENT_SHA)
    assert len(parent) == 237142 and b'\r' not in parent
    result = parent
    edits = []

    def replace(name, before, after):
        nonlocal result
        before = before.encode()
        after = after.encode()
        assert result.count(before) == 1, (name, result.count(before))
        at = result.index(before)
        updated = result[:at] + after + result[at + len(before):]
        edits.append({'name': name, 'offset_in_previous_stage': at,
                      'before': before.decode(), 'after': after.decode(),
                      'before_sha256': digest(before), 'after_sha256': digest(after),
                      'previous_source_sha256': digest(result),
                      'next_source_sha256': digest(updated)})
        result = updated

    replace('NativeFinal.dot: classify terminal Float32 with existing inline self-BEq',
            'def dot (n baseA baseB p : Nat) (A B : Array Binary32) : Binary32 :=\n'
            '  let result := dotLoop n baseA baseB p A B 0 (Float32.ofBits 0)\n'
            '  if hf : result.isNaN = false then ExecFloat.Binary.ofFloat32 result\n'
            '  else R7NaNReplay.replayEarly n baseA baseB p A B',
            'def dot (n baseA baseB p : Nat) (A B : Array Binary32) : Binary32 :=\n'
            '  let result := dotLoop n baseA baseB p A B 0 (Float32.ofBits 0)\n'
            '  if hf : R7W04.nonNaN result = true then ExecFloat.Binary.ofFloat32 result\n'
            '  else R7NaNReplay.replayEarly n baseA baseB p A B')
    replace('NativeFinal.dot_eq: transport classifier premise through existing iff',
            '    have h := (dotLoop_eq n baseA baseB p A B 0 (Float32.ofBits 0) _ rfl hf).2',
            '    have hnon := (R7W04.nonNaN_eq_true_iff _).mp hf\n'
            '    have h := (dotLoop_eq n baseA baseB p A B 0 (Float32.ofBits 0) _ rfl hnon).2')
    replace('Packed10.finish: same classifier as NativeFinal.dot',
            'def finish (n baseA baseB p : Nat) (Araw Braw : Array Binary32)\n'
            '    (result : Float32) : Binary32 :=\n'
            '  if hf : result.isNaN = false then ExecFloat.Binary.ofFloat32 result\n'
            '  else R7NaNReplay.replayEarly n baseA baseB p Araw Braw',
            'def finish (n baseA baseB p : Nat) (Araw Braw : Array Binary32)\n'
            '    (result : Float32) : Binary32 :=\n'
            '  if hf : R7W04.nonNaN result = true then ExecFloat.Binary.ofFloat32 result\n'
            '  else R7NaNReplay.replayEarly n baseA baseB p Araw Braw')

    inverse = result
    for op in reversed(edits):
        assert digest(inverse) == op['next_source_sha256']
        at = op['offset_in_previous_stage']
        before, after = op['before'].encode(), op['after'].encode()
        assert inverse[at:at + len(after)] == after
        inverse = inverse[:at] + before + inverse[at + len(after):]
        assert digest(inverse) == op['previous_source_sha256']
    assert inverse == parent
    assert len(result) <= 256000

    parser_raw = pinned(PARSER, PARSER_SHA)
    parser = load_functions(parser_raw, ['strip_comments', 'declarations'], {'re': re})
    parent_decl = parser['declarations'](parent.decode())
    candidate_decl = parser['declarations'](result.decode())
    assert parent_decl.keys() == candidate_decl.keys()
    assert {k: len(v) for k, v in parent_decl.items()} == {k: len(v) for k, v in candidate_decl.items()}
    exports = ['Submission.' + name for name in
               ['add', 'add_spec', 'mul', 'mul_spec', 'sum', 'sum_spec', 'bmm', 'bmm_spec']]
    assert all(len(candidate_decl.get(name, [])) == 1 for name in exports)
    # Replacements contain no comments. Their exact inverse recovers every parent
    # byte, including notices, all scalar/sum code and all remaining BMM code.
    assert all('/-' not in op['before'] + op['after'] and '--' not in op['before'] + op['after']
               for op in edits)
    resources = lambda text: re.findall(r'^.*\bset_option\b.*$', text, re.M)
    assert resources(parent.decode()) == resources(result.decode())

    gate_raw = pinned(GATE, GATE_SHA)
    assignments = {target.id: node.value for node in ast.parse(gate_raw.decode()).body
                   if isinstance(node, ast.Assign) for target in node.targets if isinstance(target, ast.Name)}
    policy_env = {'re': re, 'Path': Path, 'Verdict': object,
                  'SLOTS': {'full': SimpleNamespace(contract='ContractTensor')},
                  'OPTIONS': ast.literal_eval(assignments['OPTIONS']),
                  'ATTRIBUTES': ast.literal_eval(assignments['ATTRIBUTES']),
                  'BANNED': re.compile(ast.literal_eval(assignments['BANNED'].args[0]))}
    policy_env = load_functions(gate_raw, ['policy', 'options'], policy_env)
    policy_result = policy_env['policy'](SimpleNamespace(read_text=lambda: result.decode()),
                                         SimpleNamespace(slot='full'))
    assert policy_result is None, policy_result
    checks = {'exact_parent_pin': 'PASS', 'unique_three_edits': 'PASS',
              'full_byte_inverse': 'PASS', 'namespace_declaration_inventory': 'PASS',
              'unique_eight_exports_and_specs': 'PASS', 'author_comments_preserved': 'PASS',
              'resource_options_unchanged': 'PASS', 'original_gate_policy': 'PASS',
              'original_gate_sha256': GATE_SHA, 'inventory_parser_sha256': PARSER_SHA,
              'imports': re.findall(r'^import .+$', result.decode(), re.M),
              'runtime_modified_definitions': ['Submission.NativeFinal.dot', 'Submission.Packed10.finish'],
              'proof_modified_theorems': ['Submission.NativeFinal.dot_eq'],
              'all_other_bytes': 'UNCHANGED_BY_EXACT_REVERSIBLE_PATCH',
              'lean_statement': 'NOT_RUN', 'leanchecker': 'NOT_RUN', 'axiom_audit': 'NOT_RUN',
              'checksum': 'NOT_RUN', 'full_gate': 'NOT_RUN', 'generated_c_assembly': 'NOT_RUN',
              'performance': 'UNKNOWN'}
    return result, edits, checks


def main():
    ap = ArgumentParser()
    modes = ap.add_mutually_exclusive_group()
    modes.add_argument('--write', action='store_true')
    modes.add_argument('--verify', action='store_true')
    args = ap.parse_args()
    result, edits, checks = construct()
    summary = {'candidate': HERE.name, 'candidate_sha256': digest(result),
               'candidate_bytes': len(result), 'parent_sha256': PARENT_SHA,
               'delta_bytes': len(result) - 237142, 'headroom_bytes': 256000 - len(result),
               'checks': checks}
    if args.verify:
        assert (HERE / 'Kernel.lean').read_bytes() == result
        print(json.dumps(summary, indent=2))
        return
    if args.write:
        outputs = ['Kernel.lean', 'manifest.json', 'exact-inverse.json', 'static-checks.json']
        assert not any((HERE / name).exists() for name in outputs), 'Refusing to overwrite frozen source/receipts'
        manifest = dict(summary, created_at_utc=datetime.now(timezone.utc).isoformat(),
            candidate_file='Kernel.lean', parent='f01-d10-bmm-direct-rows',
            mechanism='Historical R7 self-BEq classifier migrated ONLY to NativeFinal.dot and Packed10.finish on current a066. Native loops, packing, addresses, raw NaN replay, fallback and all scalar/sum code unchanged.',
            proof='Existing R7W04.nonNaN_eq_true_iff transports dot_eq premise to unchanged dotLoop_eq. Both terminal guards agree, so unchanged finish_eq_dot remains rw [hs] <;> rfl; all downstream proofs unchanged.',
            history={'old_candidate': 'f01-r7-self-nonnan-guard',
                     'old_sha256': '6b00a89d1b1dd1fc3537d54871298583ff969169c22bd07b594eda5ab0a77e24',
                     'old_parent': 'b1696ff9a51a112c5e34e1a86ef2634c58548492e452199ee041927c6cb5a18d',
                     'old_route_status': 'Old four-endpoint source and proof1/proof2 remain NOT_RUN; no matching full receipt in current result index. R8 scalar classifiers do not cover these current BMM endpoints.',
                     'novelty': 'New exact-parent wiring experiment, not a new mechanism or measured gain'},
            lowering_evidence='Pinned R7-W06 lean.h declares lean_float32_isnan externally and defines lean_float32_beq static inline. No claim that beq was a foreign call; new candidate codegen is NOT_RUN.',
            proof_status='NOT_RUN', validation_mode='full-gate', performance='UNKNOWN',
            formal_submission='NOT_SUBMITTED', state='READY_FOR_STATEMENT', ci_owner='root')
        (HERE / 'Kernel.lean').write_bytes(result)
        for name, payload in [('manifest.json', manifest), ('exact-inverse.json', edits),
                              ('static-checks.json', summary)]:
            (HERE / name).write_bytes((json.dumps(payload, indent=2, ensure_ascii=False) + '\n').encode())
    print(json.dumps(summary, indent=2))


if __name__ == '__main__':
    main()
